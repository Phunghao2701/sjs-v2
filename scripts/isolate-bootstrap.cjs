/**
 * scripts/isolate-bootstrap.cjs
 *
 * Tự động tạo src/shared/styles/bootstrap-isolated.css từ bootstrap:
 * 1. Giữ nguyên CSS variables (:root, light/dark mode) cho các component hoạt động đúng màu sắc.
 * 2. Giữ nguyên toàn bộ Grid (.container, .row, .col) và Components (.modal, .table, .form-control, .dropdown, .toast, .alert, .progress, .nav, .offcanvas, .spinner, etc.) cho react-bootstrap.
 * 3. LOẠI BỎ hoàn toàn Reboot & Type (tránh đè font size h1-h6, margin body/p, gạch chân thẻ a của Tailwind).
 * 4. LOẠI BỎ hoàn toàn Utilities có !important (.p-5 48px, .p-0..4, .m-0..5, .border !important, .rounded !important, .text-center !important) để không đè Tailwind utility classes.
 * 5. Bọc toàn bộ trong @layer bootstrap với layer order: bootstrap < theme < base < components < utilities.
 */

const fs = require('fs');
const path = require('path');

const srcFile = path.resolve(__dirname, '../node_modules/bootstrap/dist/css/bootstrap.css');
if (!fs.existsSync(srcFile)) {
  console.error('Không tìm thấy node_modules/bootstrap/dist/css/bootstrap.css. Vui lòng chạy npm install trước.');
  process.exit(1);
}

const content = fs.readFileSync(srcFile, 'utf8');
const lines = content.split('\n');

// 1. Root variables: lines 0 to 182
const rootVars = lines.slice(0, 182).join('\n');

// 2. Components & Grid: lines 739 to 7321
const components = lines.slice(739, 7321).join('\n');

const isolated = `/* ==========================================================================
   Isolated Bootstrap 5 for Scientific Journal System FE
   Autogenerated by scripts/isolate-bootstrap.cjs
   - Contains: :root CSS variables, Grid (.row, .col), and Components (.modal, .dropdown, .form-control, etc.)
   - Excludes: Reboot (no tag resets for h1-h6, a, p, body) and Utilities (no !important utility collisions)
   - Layered: @layer bootstrap, theme, base, components, utilities
   ========================================================================== */

@layer bootstrap, theme, base, components, utilities;

@layer bootstrap {
${rootVars}

${components}
}
`;

const outDir = path.resolve(__dirname, '../src/shared/styles');
if (!fs.existsSync(outDir)) fs.mkdirSync(outDir, { recursive: true });

const outFile = path.join(outDir, 'bootstrap-isolated.css');
fs.writeFileSync(outFile, isolated, 'utf8');
console.log(`Đã tạo thành công ${outFile} (${(isolated.length / 1024).toFixed(1)} KB)`);
